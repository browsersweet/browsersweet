/*
 * Native messaging manifests can't pass arguments, so `path` points at a tiny launcher that runs
 * the copied host runtime with an absolute node path (browsers start hosts with a minimal PATH,
 * so `#!/usr/bin/env node` would miss nvm/Volta installs).
 */

/** POSIX single-quote escaping. */
export function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

export function posixLauncher(
  nodePath: string,
  cliPath: string,
  configPath: string,
): string {
  return [
    '#!/bin/sh',
    '# Browser Sweet native messaging host launcher.',
    '# Generated by `browsersweet-mcp install`; re-run install to update, `uninstall` to remove.',
    `exec ${shellQuote(nodePath)} ${shellQuote(cliPath)} host --config ${shellQuote(configPath)} -- "$@"`,
    '',
  ].join('\n');
}

export class UnsafePathError extends Error {}

function cmdQuote(value: string): string {
  if (/["%!^\r\n]/.test(value)) {
    throw new UnsafePathError(
      `can't write a .cmd launcher for a path containing " % ! ^ or a newline: ${value}`,
    );
  }
  return `"${value}"`;
}

export function windowsLauncher(
  nodePath: string,
  cliPath: string,
  configPath: string,
): string {
  return [
    '@echo off',
    'rem Browser Sweet native messaging host launcher.',
    'rem Generated by `browsersweet-mcp install`; re-run install to update, `uninstall` to remove.',
    `${cmdQuote(nodePath)} ${cmdQuote(cliPath)} host --config ${cmdQuote(configPath)} -- %*`,
    '',
  ].join('\r\n');
}
